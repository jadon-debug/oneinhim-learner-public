const { app } = require('./app-regression.cjs');
const assert = require('node:assert/strict');
(async () => {
  const a = await app();
  a.run('openBrowseShelf("podcast-shows")');
  const cards = a.window.document.querySelectorAll('#shelfDetailGrid .shelf-detail-card');
  assert.equal(cards.length, 1, 'Only the real podcast show appears');
  assert.match(cards[0].textContent, /One Gospel/);
  assert.ok(cards[0].querySelector('.shelf-detail-card-title'));
  assert.equal(a.run('homeBrowseResourceMatches(resources.find(r=>r.id==="mux_one_basics_1_1_full_video"),"podcast-shows")'), false, 'A course is not a podcast');
  assert.equal(a.run('homeBrowseResourceMatches(resources.find(r=>r.id==="aud_death_ivan_ilyich_classics"),"podcast-shows")'), false, 'An audiobook is not a podcast');
  cards[0].click();
  assert.equal(a.run('state.activeBrowseShelfKey'), 'series:one_gospel_podcast', 'A show opens its episode collection');
  assert.equal(a.window.document.querySelectorAll('#shelfDetailGrid .shelf-detail-card').length, 1);
  a.run('resources.push({...resources.find(r=>r.id==="aud_darkness_sonship_004"),id:"test_second_episode"}); openBrowseShelf("podcast-shows")');
  assert.equal(a.window.document.querySelectorAll('#shelfDetailGrid .shelf-detail-card').length, 1, 'Episodes are grouped into one show');
  assert.match(a.window.document.getElementById('shelfDetailGrid').textContent,/2 episodes/);
  assert.equal(a.run('homeResourceArtwork({id:"missing_art",format:["watch"],contentType:"lesson"})'), '', 'Missing art never impersonates another course');
  a.run('setView("onboardingView"); renderOnboarding()');
  assert.equal(a.window.document.body.classList.contains('app-chrome-hidden'),true);
  assert.equal(a.window.document.querySelectorAll('[data-onboarding-stage][aria-pressed="true"]').length,1);
  a.run('applyLanguage("nl"); renderOnboarding()');
  assert.match(a.window.document.getElementById('onboardingSupport').textContent,/later veranderen/);
  console.log('PASS: real podcast shows, episode grouping/navigation, honest artwork, selected-state accessibility and bilingual onboarding.');
})().catch(error => { console.error(error); process.exitCode=1; });
